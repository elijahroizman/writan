import { join, resolve } from 'node:path'
import { launch, start, open, check, done, TMP } from './harness.mjs'
const { browser, page, logs } = await launch()
try {
  await start(page)
  await open(page, resolve(import.meta.dirname, '../samples/S2-xlsx-cf-validation-picture.xlsx'))
  await page.waitForFunction(() => window.__sheets?.sheets.length === 1)
  const view = page.locator('.view[data-active=true]')
  const html = await view.locator('.sg-cells').innerHTML()
  check('conditional fill from a formula rule shows', html.includes('#c6efce'))
  check('conditional fill from a cell rule shows', html.includes('#ffc7ce'))
  check('color scale shows', html.includes('#f8696b') && html.includes('#63be7b'))
  check('data bars show', html.includes('linear-gradient'))
  check('icon set shows', (await view.locator('.sg-cells svg.pa').count()) >= 4)
  const pic = view.locator('.sg-picture img')
  await pic.waitFor()
  check('picture shows with its image', (await pic.evaluate((img) => img.complete && img.naturalWidth)) === 96)
  await page.evaluate(() => window.__sheets.run({ cmd: 'select', sheet: 0, anchor: [5, 0], focus: [5, 0] }))
  check('validation prompt shows', (await view.locator('.sg-prompt').textContent())?.includes('Pick a status'))
  await view.locator('.sg-dropdown-button').click()
  await page.keyboard.press('Escape')
  check('Escape closes the list', (await view.locator('.sg-dropdown-list').count()) === 0)
  await view.locator('.sg-dropdown-button').click()
  const list = await view.locator('.sg-dropdown-list').boundingBox()
  const body = await view.locator('.sg-body').boundingBox()
  check('the list opens inside the sheet', list.x >= body.x - 1)
  await view.locator('.sg-dropdown-list li', { hasText: 'Late' }).click()
  check('picking from the list fills the cell', await page.evaluate(() => window.__sheets.doc.cell(0, 5, 0).includes('"display":"Late"')))
  await page.evaluate(() => window.__sheets.run({ cmd: 'select', sheet: 0, anchor: [6, 0], focus: [6, 0] }))
  await view.locator('.sg-input').focus()
  await page.keyboard.type('Lost')
  await page.keyboard.press('Enter')
  const dialog = page.getByRole('alertdialog')
  await dialog.waitFor()
  check('a refused value explains why', (await dialog.textContent())?.includes('Pick Open, Late or Done'))
  await dialog.getByRole('button', { name: 'OK' }).click()
  check('a refused value is not put in', await page.evaluate(() => !window.__sheets.doc.cell(0, 6, 0).includes('Lost')))
  await page.screenshot({ path: join(TMP, `excel-visuals-${process.env.ENGINE ?? 'chromium'}.png`) })
} finally { await done(browser, logs) }
