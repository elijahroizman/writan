// The LaTeX commands and environments offered as you type `\` (and inside `\begin{…}`), as
// VS Code's LaTeX extension lists them.
//
// One command per line: `name|arguments`. In the arguments `{}` is a slot the cursor visits (Tab
// moves to the next) and `<>` is one without braces; anything else is typed as it is.

export interface LatexCommand {
  name: string
  args: string
}

export interface LatexEnvironment {
  name: string
  /** Typed straight after \begin{name}, like a table's column letters. */
  after: string
  /** What goes between \begin and \end (lines split at a literal `\n`); `@` is where the
   * cursor lands, or the empty line inside when there's none. */
  body: string
}

