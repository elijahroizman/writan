function parseCommands(): LatexCommand[] {
  return COMMANDS.split('\n')
    .filter((l) => l.trim())
    .map((l) => {
      const bar = l.indexOf('|')
      return bar < 0 ? { name: l.trim(), args: '' } : { name: l.slice(0, bar).trim(), args: l.slice(bar + 1) }
    })
}

function parseEnvironments(): LatexEnvironment[] {
  return ENVIRONMENTS.split('\n')
    .filter((l) => l.trim())
    .map((l) => {
      const [name, after = '', body = ''] = l.split('|')
      return { name, after, body: body.replace(/\\n(?![a-z])/g, '\n') }
    })
}

export const LATEX_COMMANDS = parseCommands()
export const LATEX_ENVIRONMENTS = parseEnvironments()
